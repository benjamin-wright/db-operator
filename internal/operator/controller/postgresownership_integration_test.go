//go:build integration

package controller

import (
	. "github.com/benjamin-wright/db-operator/internal/test_utils"
	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
)

var _ = Describe("PostgresCredential ownership sessions", func() {
	It("fences global mutations after lock loss and serializes surviving database work", func() {
		ns, _, lookup, secret := NewDatabase("credential-sessions")
		DeferCleanup(func() { _ = K8sClient.Delete(Ctx, ns) })
		WaitForDatabase(lookup)
		admin, closeAdmin := ConnectToDatabase(lookup, secret)
		DeferCleanup(closeAdmin)
		_, err := admin.Exec("CREATE DATABASE session_policy")
		Expect(err).NotTo(HaveOccurred())
		originalDB, closeOriginal := ConnectToDatabase(lookup, secret)
		DeferCleanup(closeOriginal)
		original, err := acquireUserOwnership(originalDB, "session_user", "owner", 1, false, func() error { return nil })
		Expect(err).NotTo(HaveOccurred())
		DeferCleanup(func() { _ = original.Close() })
		Expect(original.Manager().EnsureUserExists("", "", "", "session_user", "initial")).To(Succeed())
		targetDB, closeTarget := ConnectToDatabaseNamed(lookup, secret, "session_policy")
		DeferCleanup(closeTarget)
		target, err := original.lockDatabase(targetDB)
		Expect(err).NotTo(HaveOccurred())
		DeferCleanup(func() { _ = target.Close() })
		_, err = target.Exec("CREATE TABLE effects (value text)")
		Expect(err).NotTo(HaveOccurred())
		var originalPID int
		Expect(original.session.QueryRowContext(Ctx, "SELECT pg_backend_pid()").Scan(&originalPID)).To(Succeed())
		var killed bool
		Expect(admin.QueryRow("SELECT pg_terminate_backend($1, 5000)", originalPID).Scan(&killed)).To(Succeed())
		Expect(killed).To(BeTrue())
		Expect(original.Manager().SetUserPassword("", "", "", "session_user", "stale")).NotTo(Succeed())
		Expect(original.Manager().EnableUser("", "", "", "session_user")).NotTo(Succeed())
		Expect(original.Forget()).NotTo(Succeed())
		successorDB, closeSuccessor := ConnectToDatabase(lookup, secret)
		DeferCleanup(closeSuccessor)
		successor, err := acquireUserOwnership(successorDB, "session_user", "owner", 2, true, func() error { return nil })
		Expect(err).NotTo(HaveOccurred())
		DeferCleanup(func() { _ = successor.Close() })
		blockedDB, closeBlocked := ConnectToDatabaseNamed(lookup, secret, "session_policy")
		DeferCleanup(closeBlocked)
		_, err = successor.lockDatabase(blockedDB)
		Expect(err).To(MatchError(ContainSubstring("already in progress")))
		_, err = target.Exec("INSERT INTO effects VALUES ('accepted predecessor')")
		Expect(err).NotTo(HaveOccurred())
		Expect(target.Close()).To(Succeed())
		nextDB, closeNext := ConnectToDatabaseNamed(lookup, secret, "session_policy")
		DeferCleanup(closeNext)
		next, err := successor.lockDatabase(nextDB)
		Expect(err).NotTo(HaveOccurred())
		DeferCleanup(func() { _ = next.Close() })
		_, err = next.Exec("DELETE FROM effects")
		Expect(err).NotTo(HaveOccurred())
		staleDB, closeStale := ConnectToDatabaseNamed(lookup, secret, "session_policy")
		DeferCleanup(closeStale)
		Expect(next.Close()).To(Succeed())
		_, err = original.lockDatabase(staleDB)
		Expect(err).To(HaveOccurred())
		Expect(successor.Manager().SetUserPassword("", "", "", "session_user", "current")).To(Succeed())
	})

	It("never reconnects a terminated database mutation session", func() {
		ns, _, lookup, secret := NewDatabase("credential-target-loss")
		DeferCleanup(func() { _ = K8sClient.Delete(Ctx, ns) })
		WaitForDatabase(lookup)
		admin, closeAdmin := ConnectToDatabase(lookup, secret)
		DeferCleanup(closeAdmin)
		_, err := admin.Exec("CREATE DATABASE session_target")
		Expect(err).NotTo(HaveOccurred())
		ownerDB, closeOwner := ConnectToDatabase(lookup, secret)
		DeferCleanup(closeOwner)
		owner, err := acquireUserOwnership(ownerDB, "session_user", "owner", 1, false, func() error { return nil })
		Expect(err).NotTo(HaveOccurred())
		DeferCleanup(func() { _ = owner.Close() })
		targetDB, closeTarget := ConnectToDatabaseNamed(lookup, secret, "session_target")
		DeferCleanup(closeTarget)
		target, err := owner.lockDatabase(targetDB)
		Expect(err).NotTo(HaveOccurred())
		DeferCleanup(func() { _ = target.Close() })
		var pid int
		Expect(target.QueryRow("SELECT pg_backend_pid()").Scan(&pid)).To(Succeed())
		var killed bool
		Expect(admin.QueryRow("SELECT pg_terminate_backend($1, 5000)", pid).Scan(&killed)).To(Succeed())
		Expect(killed).To(BeTrue())
		_, err = target.Exec("CREATE TABLE stale_write (value text)")
		Expect(err).To(HaveOccurred())
		_, err = target.Exec("CREATE TABLE retried_stale_write (value text)")
		Expect(err).To(HaveOccurred())
	})
})
